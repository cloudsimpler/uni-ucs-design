const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const vue = require('vue');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');

(async () => {
  const filename = path.resolve(__dirname, '../components/ucs-image/ucs-image.vue');
  const { descriptor, errors } = parse(fs.readFileSync(filename, 'utf8'), { filename });
  assert.deepEqual(errors, []);
  const script = compileScript(descriptor, { id: 'ucs-image-test' });
  const template = compileTemplate({ source: descriptor.template.content, filename, id: 'ucs-image-test', compilerOptions: { bindingMetadata: script.bindings } });
  assert.deepEqual(template.errors, []);
  const cache = new Map();
  const vueModule = new vm.SyntheticModule(Object.keys(vue), function () {
    for (const key of Object.keys(vue)) this.setExport(key, vue[key]);
  });
  function load(file, text) {
    if (!cache.has(file)) cache.set(file, new vm.SourceTextModule(text ?? fs.readFileSync(file, 'utf8'), { identifier: file }));
    return cache.get(file);
  }
  const entry = load(filename, script.content);
  await entry.link((specifier, parent) => specifier === 'vue' ? vueModule : load(path.resolve(path.dirname(parent.identifier), specifier)));
  await entry.evaluate();
  const component = entry.namespace.default;
  const props = vue.reactive(Object.fromEntries(Object.entries(component.props).map(([name, definition]) => [name, definition.default])));
  const events = [];
  let listener = () => {};
  const scope = vue.effectScope();
  const state = scope.run(() => component.setup(props, { expose() {}, emit: (...event) => { events.push(event); listener(...event); } }));
  const core = cache.get(path.resolve(__dirname, '../core/config.js')).namespace;
  try {
    assert.equal(component.options.virtualHost, true);
    assert.deepEqual(state.imageStyle.value, { width: '100px', height: '100px', borderRadius: '0px', backgroundColor: 'transparent' });
    props.width = 80;
    props.radius = '50%';
    assert.equal(state.imageStyle.value.height, '80px');
    assert.equal(state.imageStyle.value.borderRadius, '50%');
    props.height = 40;
    assert.equal(state.imageStyle.value.height, '40px');
    core.updateConfig({ typographyOffset: 8 });
    assert.equal(state.imageStyle.value.width, '80px');
    props.height = '0';
    props.width = '100%';
    assert.equal(state.imageStyle.value.height, '100%');
    props.height = '0px';
    assert.equal(state.imageStyle.value.height, '0px');
    props.width = 0;
    assert.equal(state.imageStyle.value.width, '0px');
    props.width = Infinity;
    props.height = NaN;
    props.radius = -1;
    assert.equal(state.imageStyle.value.width, '100px');
    assert.equal(state.imageStyle.value.height, '100px');
    assert.equal(state.imageStyle.value.borderRadius, '0px');
    props.placeholderColor = ['#123456', 'gray-3'];
    assert.equal(state.imageStyle.value.backgroundColor, '#123456');
    core.setThemeMode('dark');
    assert.equal(state.imageStyle.value.backgroundColor, core.getThemeColor('gray-3'));
    props.placeholderColor = ['primary-6'];
    core.setThemeColor('primary', '#1890FF');
    assert.equal(state.imageStyle.value.backgroundColor, core.getThemeColor('primary-6'));
    props.placeholderColor = [];
    assert.throws(() => state.imageStyle.value, TypeError);
    props.placeholderColor = ['transparent', null];
    assert.equal(state.imageStyle.value.backgroundColor, 'transparent');
    props.placeholderColor = 'gray-99';
    assert.equal(state.imageStyle.value.backgroundColor, 'gray-99');

    props.src = ' /primary.png ';
    props.errorSrc = '/fallback.png';
    const primary = state.imageState.value;
    const failure = { detail: { errMsg: 'failed' } };
    listener = name => { if (name === 'error') assert.equal(state.imageState.value.src, '/primary.png'); };
    primary.onError(failure);
    assert.equal(events.at(-1)[1], failure);
    const fallback = state.imageState.value;
    assert.equal(fallback.src, '/fallback.png');
    assert.notEqual(fallback.id, primary.id);
    listener = () => {};
    fallback.onError(failure);
    assert.equal(state.imageState.value, fallback);
    props.errorSrc = '/another-fallback.png';
    fallback.onError(failure);
    assert.equal(state.imageState.value, fallback);
    props.src = '/new-primary.png';
    const next = state.imageState.value;
    const count = events.length;
    primary.onError(failure);
    fallback.onLoad({});
    assert.equal(events.length, count);
    assert.equal(state.imageState.value, next);
    const loaded = { detail: { width: 80, height: 40 } };
    next.onLoad(loaded);
    assert.deepEqual(events.at(-1), ['load', loaded]);
    listener = name => { if (name === 'error') props.src = '/chosen-by-parent.png'; };
    next.onError(failure);
    assert.equal(state.imageState.value.src, '/chosen-by-parent.png');
    listener = () => {};
    props.errorSrc = '/chosen-by-parent.png';
    const identical = state.imageState.value;
    identical.onError(failure);
    assert.equal(state.imageState.value, identical);
    props.errorSrc = '';
    props.src = '/no-fallback.png';
    const withoutFallback = state.imageState.value;
    withoutFallback.onError(failure);
    assert.equal(state.imageState.value, withoutFallback);
    const tap = {};
    state.onTap(tap);
    state.onLongPress(tap);
    assert.deepEqual(events.slice(-3), [['tap', tap], ['click', tap], ['longpress', tap]]);
    console.log('PASS image SFC compilation, dimensions, theme backgrounds, fallback bounds, stale events, synchronous parent updates and event forwarding');
  } finally {
    scope.stop();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
