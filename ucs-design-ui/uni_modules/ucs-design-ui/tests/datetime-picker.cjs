const path = require('node:path');
const assert = require('node:assert/strict');
const { runtime, renderer } = require('./helpers/runtime.cjs');
(async () => {
  const r = runtime(), { vue } = r;
  const logic = await r.importFile(path.resolve(__dirname, '../components/ucs-datetime-picker/datetime.js'));
  assert.equal(logic.daysInMonth(2000, 2), 29); assert.equal(logic.daysInMonth(1900, 2), 28);
  for (const text of ['2026-02-29', '2026-00-01', '2026-13-01', '2026-01-00', '2026-1-1']) assert.equal(logic.parseValue(text, 'date'), null);
  assert.equal(logic.parseValue('24:00', 'time'), null);
  const { session } = logic.createSession('datetime', '2026-02-10 10:30', '2026-03-02 12:15', '');
  let draft = logic.clampValue([2026, 2, 31, 9, 0], session);
  assert.deepEqual(Array.from(draft), [2026, 2, 28, 9, 0]);
  let columns = logic.getColumns([2026, 2, 10, 10, 30], session);
  assert.equal(columns[2][0], 10); assert.equal(columns[3][0], 10); assert.equal(columns[4][0], 30);
  columns = logic.getColumns([2026, 3, 2, 12, 15], session);
  assert.equal(columns[2].at(-1), 2); assert.equal(columns[4].at(-1), 15);
  assert.throws(() => logic.createSession('date', '2026-02-01', '2026-01-01', ''), /min/);
  const Picker = (await r.importFile(path.resolve(__dirname, '../components/ucs-datetime-picker/ucs-datetime-picker.vue'))).default;
  const Button = (await r.importFile(path.resolve(__dirname, '../components/ucs-button/ucs-button.vue'))).default;
  const Popup = (await r.importFile(path.resolve(__dirname, '../components/ucs-popup/ucs-popup.vue'))).default;
  const core = await r.importFile(path.resolve(__dirname, '../index.js'));
  const props = vue.reactive({ mode: 'date', modelValue: '2028-01-31' });
  const ref = vue.ref(), events = [];
  const { renderer: rr, node } = renderer();
  const app = rr.createApp({ render: () => vue.h(Picker, { ...props, ref, 'onUpdate:modelValue': value => events.push(['value', value]), onConfirm: value => events.push(['confirm', value]), onCancel: value => events.push(['cancel', value]), onError: error => events.push(['error', error]), onClose: reason => events.push(['close', reason]) }) });
  app.component('ucs-popup', Popup); app.component('ucs-button', Button);
  for (const name of ['ucs-text', 'ucs-safe-area', 'ucs-icon', 'ucs-spinner']) app.component(name, { render: () => vue.h('view') });
  const host = node('root'); app.mount(host); const s = ref.value.$.setupState;
  function findNodes(n, predicate) { return [...(predicate(n) ? [n] : []), ...n.children.flatMap(child => findNodes(child, predicate))]; }
  const actionNodes = () => findNodes(host, n => n.props.class === 'ucs-datetime-picker__close');
  assert.equal(ref.value.open(), true); await r.flush();
  assert.equal(findNodes(host, n => n.type === 'button').length, 1);
  assert(!Object.hasOwn(Picker.props, 'cancelText'));
  assert.equal(actionNodes().length, 1);
  const indexes = Array.from(s.indexes); indexes[1] = 1;
  s.onChange({ detail: { value: indexes } }); assert.equal(logic.formatValue(s.draft, 'date'), '2028-02-29');
  assert.equal(events.length, 0); ref.value.open(); assert.equal(s.draft[1], 2);
  s.busy = true; await r.flush();
  assert.equal(findNodes(host, n => n.type === 'button')[0].props.disabled, true);
  assert.equal(s.confirm(), false); s.busy = false; await r.flush();
  findNodes(host, n => n.type === 'button')[0].props.onClick({}); assert.deepEqual(events.slice(-3), [['close', 'confirm'], ['value', '2028-02-29'], ['confirm', '2028-02-29']]);
  assert.equal(s.confirm(), false);
  ref.value.open(); await r.flush(); assert.equal(s.draft[1], 1); actionNodes()[0].props.onTap(); assert.equal(events.at(-1)[0], 'cancel');
  props.mode = 'time'; props.modelValue = '10:35'; props.min = '10:30'; props.max = '11:15'; await r.flush();
  ref.value.open(); await r.flush(); assert.equal(s.columns[1][0], 30);
  props.modelValue = '11:10'; await r.flush(); assert.equal(s.draft[0], 10);
  const before = [...s.draft]; s.onChange({ detail: { value: [100, 0] } }); assert.deepEqual([...s.draft], before);
  core.setLanguage('en'); assert.equal(s.confirmLabel, 'Confirm'); assert.equal(s.units[0], 'h');
  ref.value.close();
  props.min = 'invalid'; await r.flush(); assert.equal(ref.value.open(), false); assert.equal(events.at(-1)[0], 'error');
  app.unmount();
  console.log('PASS datetime picker: strict calendar parsing, leap years, boundary columns, draft isolation, ref lifecycle, confirmation guard, locale and invalid config');
})().catch(error => { console.error(error); process.exitCode = 1; });
