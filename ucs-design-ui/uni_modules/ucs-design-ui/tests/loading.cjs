const path = require('node:path');
const assert = require('node:assert/strict');
const { runtime, renderer } = require('./helpers/runtime.cjs');
(async () => {
  const r = runtime(), { vue } = r;
  const Loading = (await r.importFile(path.resolve(__dirname, '../components/ucs-loading/ucs-loading.vue'))).default;
  const Popup = (await r.importFile(path.resolve(__dirname, '../components/ucs-popup/ucs-popup.vue'))).default;
  const Page = (await r.importFile(path.resolve(__dirname, '../components/ucs-page/ucs-page.vue'))).default;
  const core = await r.importFile(path.resolve(__dirname, '../index.js'));
  const refs = { a: vue.ref(), b: vue.ref(), popup: vue.ref(), page: vue.ref() };
  const { renderer: rr, node } = renderer();
  let spinnerMounts = 0, spinnerUnmounts = 0;
  const app = rr.createApp({ render: () => vue.h('view', [vue.h(Loading, { ref: refs.a }), vue.h(Loading, { ref: refs.b }),
    vue.h(Popup, { ref: refs.popup, safeAreaInsetBottom: false }), vue.h(Page, { ref: refs.page })]) });
  app.component('ucs-loading', Loading);
  app.component('ucs-spinner', { setup() { spinnerMounts++; vue.onBeforeUnmount(() => spinnerUnmounts++); return () => vue.h('view'); } });
  for (const name of ['ucs-text', 'ucs-icon', 'ucs-toast', 'ucs-safe-area']) app.component(name, { render: () => vue.h('view') });
  const host = node('root'); app.mount(host);
  const a = refs.a.value, b = refs.b.value, p = refs.popup.value, page = refs.page.value;
  const s = a.$.setupState, ps = p.$.setupState;
  assert.equal(s.rootStyle.pointerEvents, 'none'); assert.equal(s.entry, null); assert.equal(r.timers.size, 0);
  assert.equal(a.show(), true); assert.equal(s.entry.text, ''); assert.equal(s.rootStyle.pointerEvents, 'auto');
  const mask = host.children[0].children[0];
  let prevented = 0, stopped = 0;
  mask.props.onTouchmove({ preventDefault() { prevented++; }, stopPropagation() { stopped++; } });
  assert.equal(prevented, 1); assert.equal(stopped, 1);
  await r.flush(); assert.equal(s.ready, true); const mounted = spinnerMounts;
  const z = s.rootStyle.zIndex;
  assert.equal(a.show({ text: ' 正在提交 ' }), true); await r.flush(); assert.equal(s.entry.text, '正在提交');
  assert.equal(s.ready, true); assert.equal(s.rootStyle.zIndex, z); assert.equal(spinnerMounts, mounted);
  assert.equal(a.show({ text: 123 }), false); assert.equal(a.show(null), false); assert.equal(s.entry.text, '正在提交');
  s.onMask(); assert(s.entry); r.advance(60000); assert(s.entry); assert.equal(r.timers.size, 0);
  p.open(); await r.flush(); assert.equal(ps.hostStyle.pointerEvents, 'none'); assert(s.rootStyle.zIndex > ps.viewportStyle.zIndex);
  b.show('第二个加载'); await r.flush(); assert.equal(s.rootStyle.pointerEvents, 'none');
  p.close(); p.open(); await r.flush(); assert.equal(ps.hostStyle.pointerEvents, 'none');
  assert(b.$.setupState.rootStyle.zIndex > s.rootStyle.zIndex); assert(s.rootStyle.zIndex > ps.viewportStyle.zIndex);
  assert.equal(b.$.setupState.rootStyle.pointerEvents, 'auto'); b.hide(); assert.equal(s.rootStyle.pointerEvents, 'auto');
  a.hide(); assert.equal(ps.hostStyle.pointerEvents, 'auto'); await r.flush(); assert.equal(s.entry, null);
  a.show('旧请求'); a.hide(); await r.flush(); assert.equal(s.entry, null); assert.equal(s.ready, false);
  // A pending native layout cannot reopen after hide or overwrite the next show.
  a.show('等待布局'); await vue.nextTick();
  let resolveLayout;
  s.panelRef.getBoundingClientRectAsync = () => new Promise(resolve => { resolveLayout = resolve; });
  await r.flush(); assert.equal(s.ready, false); assert.equal(s.rootStyle.pointerEvents, 'auto');
  const oldLayout = resolveLayout;
  a.hide(); a.show('新请求'); await r.flush(); assert.equal(s.entry.text, '新请求'); assert.equal(s.ready, false);
  oldLayout({}); await r.flush(); assert.equal(s.entry.text, '新请求'); assert.equal(s.ready, false);
  resolveLayout({}); await r.flush(); assert.equal(s.ready, true);
  a.hide(); a.show(); await vue.nextTick(); s.panelRef.getBoundingClientRectAsync = () => Promise.reject(Error('layout'));
  await r.flush(); assert.equal(s.ready, true);
  core.setThemeMode('dark'); await r.flush(); assert.equal(s.foregroundColor, '#181818');
  assert.equal(s.panelStyle.backgroundColor, 'rgba(255, 255, 255, 0.92)'); a.hide();
  assert.equal(page.showMaskLoading('页面加载'), true); await r.flush();
  assert.equal(page.$.setupState.maskLoadingRef.$.setupState.entry.text, '页面加载');
  page.hideMaskLoading(); page.hideMaskLoading(); assert.equal(page.$.setupState.loading, false);
  p.close(); await r.flush(); r.advance(240); await r.flush();
  page.showMaskLoading(); a.show(); await r.flush(); app.unmount();
  assert.equal(a.show(), false); a.hide(); assert.equal(page.showMaskLoading(), false);
  assert.equal(r.timers.size, 0); assert.equal(spinnerMounts, spinnerUnmounts);
  console.log('PASS loading: manual lifetime, immediate blocking, repeat updates, native layout races/failure, theme, popup priority, multiple instances, page forwarding and cleanup');
})().catch(error => { console.error(error); process.exitCode = 1; });
