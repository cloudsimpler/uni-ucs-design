const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { runtime } = require('./helpers/runtime.cjs');
(async () => {
  const r = runtime(); r.context.wallTime = 100000;
  vm.runInContext('Date.now = () => wallTime', r.context);
  const { useCountdown } = await r.importFile(path.resolve(__dirname, '../index.js'));
  const tick = ms => { r.context.wallTime += ms; r.advance(ms); };
  let ends = 0;
  const c = useCountdown({ duration: 2500, onFinish: () => ends++ });
  assert.equal(c.remaining.value, 2500); assert.equal(c.totalSeconds.value, 3); assert.equal(c.running.value, false);
  assert.equal(r.timers.size, 0); assert.equal(c.start(), true); assert.equal(c.start(), false); assert.equal(r.timers.size, 1);
  tick(1000); assert.equal(c.remaining.value, 1500); assert.equal(c.totalSeconds.value, 2);
  r.context.wallTime += 200; c.pause(); assert.equal(c.remaining.value, 1300); assert.equal(r.timers.size, 0);
  tick(5000); assert.equal(c.remaining.value, 1300); assert.equal(c.sync(), false);
  c.start(); tick(1000); assert.equal(c.remaining.value, 300); tick(300);
  assert.equal(c.finished.value, true); assert.equal(c.running.value, false); assert.equal(ends, 1); assert.equal(r.timers.size, 0);
  assert.equal(c.start(), false); assert.equal(c.sync(), false); assert.equal(c.pause(), false); tick(10000); assert.equal(ends, 1);
  c.reset(); assert.equal(c.remaining.value, 2500); assert.equal(c.finished.value, false);
  c.start(); r.context.wallTime += 10000; // suspended timers: sync must use wall time, not tick counts
  c.sync(); assert.equal(c.remaining.value, 0); assert.equal(ends, 2); assert.equal(r.timers.size, 0);
  c.reset(90061001); assert.equal(c.totalSeconds.value, 90062);
  assert.deepEqual({ ...c.time.value }, { days: 1, hours: 1, minutes: 1, seconds: 2 });
  assert.equal(Object.isFrozen(c.time.value), true);
  c.reset(); assert.equal(c.remaining.value, 90061001);
  c.reset(0); assert.equal(c.finished.value, true); assert.equal(c.start(), false); assert.equal(ends, 2);
  c.reset(1000); c.start(); r.context.wallTime += 1001; c.pause(); assert.equal(ends, 3); assert.equal(c.finished.value, true);
  c.reset(2500); c.start(); r.context.wallTime += 10000; c.dispose(); assert.equal(ends, 3); assert.equal(c.remaining.value, 0);
  assert.equal(c.reset(), false); assert.equal(c.start(), false); assert.equal(r.timers.size, 0);

  let restarts = 0, restarting;
  restarting = useCountdown({ duration: 100, onFinish() { restarts++; if (restarts === 1) { restarting.reset(); restarting.start(); } } });
  restarting.start(); tick(100); assert.equal(restarts, 1); assert.equal(restarting.running.value, true); assert.equal(r.timers.size, 1);
  tick(100); assert.equal(restarts, 2); assert.equal(r.timers.size, 0);
  // A synchronous watcher may reset/restart the next round before the old round notifies.
  let watchedEnds = 0;
  const watched = useCountdown({ duration: 100, onFinish() { watchedEnds++; } });
  const unwatch = r.vue.watch(watched.finished, value => { if (value) { watched.reset(); watched.start(); } }, { flush: 'sync' });
  watched.start(); tick(100); assert.equal(watchedEnds, 1); assert.equal(watched.running.value, true); assert.equal(r.timers.size, 1);
  tick(100); assert.equal(watchedEnds, 2);
  unwatch(); watched.dispose(); assert.equal(r.timers.size, 0);
  let scopeCountdown; const scope = r.vue.effectScope();
  scope.run(() => { scopeCountdown = useCountdown({ autoStart: true }); });
  assert.equal(r.timers.size, 1); scope.stop(); assert.equal(r.timers.size, 0);
  assert.equal(scopeCountdown.start(), false);
  const pausedOnWatch = useCountdown({ duration: 500 });
  const stop = r.vue.watch(pausedOnWatch.running, value => { if (value) pausedOnWatch.pause(); }, { flush: 'sync' });
  pausedOnWatch.start(); assert.equal(r.timers.size, 0); assert.equal(pausedOnWatch.running.value, false); stop(); pausedOnWatch.dispose();
  const throws = useCountdown({ duration: 1, onFinish() { throw Error('callback'); } });
  throws.start(); assert.throws(() => tick(1), /callback/); assert.equal(throws.running.value, false); assert.equal(r.timers.size, 0);
  const long = useCountdown({ duration: 1e12, interval: 1e11, autoStart: true });
  r.advance(2147483646); assert.equal(long.remaining.value, 1e12);
  r.context.wallTime += 2147483647; r.advance(1); assert.equal(long.remaining.value, 1e12 - 2147483647); long.dispose();
  const empty = useCountdown({ duration: 0, autoStart: true, onFinish() { throw Error('initial zero'); } }); assert.equal(empty.finished.value, true);
  for (const duration of [-1, NaN, Infinity, '1']) assert.throws(() => useCountdown({ duration }), /duration/);
  for (const interval of [0, -1, NaN, Infinity, '1']) assert.throws(() => useCountdown({ interval }), /interval/);
  assert.throws(() => useCountdown({ autoStart: 1 }), /autoStart/); assert.throws(() => useCountdown({ onFinish: 1 }), /onFinish/);
  assert.throws(() => restarting.reset(-1), /duration/); assert.equal(r.timers.size, 0);
  console.log('PASS countdown: start/pause/resume/reset, wall-clock correction, rounding, completion/reentry, single timer, scope disposal and validation');
})().catch(error => { console.error(error); process.exitCode = 1; });
